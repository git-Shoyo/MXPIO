import tempfile
import unittest
from pathlib import Path

from mxpio.core import MXPIOError, apply, check, plan, read_manifest, rollback, transform_main

IOC = '''Mcu.CPN=STM32G431CBU6
ProjectManager.FirmwarePackage=STM32Cube FW_G4 V1.6.3
'''
MAIN = '''/* CubeMX autogenerated file */
#include "main.h"
#include "tim.h"
#include "i2c.h"
/* USER CODE BEGIN Includes */
#include <math.h>
/* USER CODE END Includes */
TIM_HandleTypeDef htim2;
/* Private function prototypes -----------------------------------------------*/
void SystemClock_Config(void);
static void MX_GPIO_Init(void);
/* USER CODE BEGIN 0 */
/* USER CODE END 0 */
int main(void)
{
  /* USER CODE BEGIN 1 */
  /* USER CODE END 1 */
  HAL_Init();
  /* USER CODE BEGIN Init */
  /* USER CODE END Init */
  SystemClock_Config();
  /* USER CODE BEGIN SysInit */
  /* USER CODE END SysInit */
  MX_GPIO_Init();
  MX_TIM2_Init();
  /* USER CODE BEGIN 2 */
  /* USER CODE END 2 */
  while (1)
  {
    /* USER CODE BEGIN WHILE */
    /* USER CODE END WHILE */
    /* USER CODE BEGIN 3 */
    /* USER CODE END 3 */
  }
  /* USER CODE BEGIN 4 */
  /* USER CODE END 4 */
}
void SystemClock_Config(void) { /* RCC */ }
static void MX_GPIO_Init(void) { /* GPIO */ }
/* USER CODE BEGIN 5 */
/* USER CODE END 5 */
'''


class WorkFlowTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.source = self.root / 'cube'
        self.output = self.root / 'pio'
        (self.source / 'Core' / 'Inc').mkdir(parents=True)
        (self.source / 'Core' / 'Src').mkdir(parents=True)
        (self.source / 'cube.ioc').write_text(IOC)
        (self.source / 'Core/Src/main.c').write_text(MAIN)
        (self.source / 'Core/Src/stm32g4xx_hal_msp.c').write_text('void HAL_MspInit(void) {}')
        (self.source / 'Core/Src/stm32g4xx_it.c').write_text('void TIM7_IRQHandler(void) {}')
        (self.source / 'Core/Src/system_stm32g4xx.c').write_text('should not be copied')
        (self.source / 'Core/Inc/main.h').write_text('#include "stm32g4xx_hal.h"')
        (self.source / 'Core/Inc/stm32g4xx_hal_conf.h').write_text('#define HAL_TIM_MODULE_ENABLED')
        (self.source / 'Core/Inc/tim.h').write_text('extern int tim;')
        (self.source / 'Core/Inc/i2c.h').write_text('extern int i2c;')

    def tearDown(self):
        self.tmp.cleanup()

    def _init(self):
        p = plan(self.source, self.output, None, None, 'mxpio')
        self.assertEqual(p.conflicts, [])
        apply(self.output, p, None)
        return read_manifest(self.output)

    def test_init_and_sync_and_rollback(self):
        old = self._init()
        self.assertFalse(check(self.output))
        generated = (self.output / 'src/mx_generated/mx_boot.c').read_text()
        self.assertIn('void MX_Init(void)', generated)
        self.assertIn('HAL_Init();', generated)
        self.assertIn('MX_TIM2_Init();', generated)
        self.assertNotIn('while (1)', generated)
        self.assertIn('void SystemClock_Config(void)', generated)
        self.assertIn('#include <math.h>', generated)
        self.assertFalse((self.output / 'src/mx_generated/system_stm32g4xx.c').exists())
        user = self.output / 'src/main.cpp'
        user.write_text('// user C++ should stay\nint main() { return 0; }\n')
        (self.source / 'Core/Src/main.c').write_text(MAIN.replace('  MX_TIM2_Init();', '  MX_TIM2_Init();\n  MX_TIM3_Init();'))
        new = plan(self.source, self.output, old, old['config']['board'], 'mxpio')
        self.assertEqual(new.update, ['src/mx_generated/mx_boot.c'])
        snapshot = apply(self.output, new, old)
        self.assertTrue(snapshot.is_file())
        self.assertIn('MX_TIM3_Init();', (self.output / 'src/mx_generated/mx_boot.c').read_text())
        self.assertIn('// user C++ should stay', user.read_text())
        self.assertFalse(check(self.output))
        rollback(self.output)
        self.assertNotIn('MX_TIM3_Init();', (self.output / 'src/mx_generated/mx_boot.c').read_text())
        self.assertIn('// user C++ should stay', user.read_text())

    def test_manual_generated_modification_aborts(self):
        old = self._init()
        f = self.output / 'src/mx_generated/mx_boot.c'
        f.write_text(f.read_text() + '\n// manual edit')
        (self.source / 'Core/Src/main.c').write_text(MAIN + '\n// new generated content')
        p = plan(self.source, self.output, old, old['config']['board'], 'mxpio')
        self.assertTrue(p.conflicts)
        with self.assertRaises(MXPIOError):
            apply(self.output, p, old)
        self.assertIn('// manual edit', f.read_text())

    def test_user_changes_ini_are_preserved(self):
        old = self._init()
        ini = self.output / 'platformio.ini'
        ini.write_text(ini.read_text() + '\nmonitor_speed = 115200\n')
        p = plan(self.source, self.output, old, old['config']['board'], 'mxpio')
        self.assertFalse(p.conflicts)
        self.assertIn('platformio.ini', p.unchanged)
        self.assertFalse(p.changed)
        self.assertIn('monitor_speed', ini.read_text())

    def test_mx_init_header_exposes_hal_and_pin_definitions(self):
        self._init()
        header = (self.output / 'include/mxpio/mx_init.h').read_text()
        self.assertIn('#include "main.h"', header)
        self.assertIn('void MX_Init(void);', header)
        self.assertIn('extern "C"', header)
        self.assertIn('#include "mxpio/mx_init.h"', (self.output / 'src/main.cpp').read_text())

    def test_main_loop_code_aborts(self):
        main = MAIN.replace('    /* USER CODE BEGIN WHILE */', '    HAL_Delay(100);\n    /* USER CODE BEGIN WHILE */')
        with self.assertRaisesRegex(MXPIOError, 'while'):
            transform_main(main)

    def test_file_add_remove(self):
        old = self._init()
        source_file = self.source / 'Core/Src/usart.c'
        source_file.write_text('int USARTInit(void) {return 1;}')
        p = plan(self.source, self.output, old, old['config']['board'], 'mxpio')
        self.assertIn('src/mx_generated/usart.c', p.add)
        apply(self.output, p, old)
        old = read_manifest(self.output)
        source_file.unlink()
        p2 = plan(self.source, self.output, old, old['config']['board'], 'mxpio')
        self.assertIn('src/mx_generated/usart.c', p2.remove)
        apply(self.output, p2, old)
        self.assertFalse((self.output / 'src/mx_generated/usart.c').exists())

    def test_ioc_without_generated_code_errors(self):
        only_ioc = self.root / 'ioc_only'
        only_ioc.mkdir()
        (only_ioc / 'cube.ioc').write_text(IOC)
        with self.assertRaisesRegex(MXPIOError, 'GENERATE CODE'):
            plan(only_ioc, self.output, None, None, None)

    def test_conflict_with_existing_file_aborts(self):
        (self.output / 'src').mkdir(parents=True)
        (self.output / 'src/main.cpp').write_text('preserve existing code!')
        p = plan(self.source, self.output, None, None, 'mxpio')
        self.assertTrue(p.conflicts)
        self.assertIn('preserve existing code!', (self.output / 'src/main.cpp').read_text())

    def test_main_comments_and_strings_do_not_confuse_braces(self):
        main = MAIN.replace('  HAL_Init();', '  char *s="while (1) { }"; /* } */\n  HAL_Init();')
        code, _ = transform_main(main)
        self.assertIn('void MX_Init(void)', code)
        self.assertIn('char *s=', code)


if __name__ == '__main__':
    unittest.main()

class NoModificationTests(unittest.TestCase):
    def test_input_main_has_no_main(self):
        with self.assertRaises(MXPIOError):
            transform_main('int other(void) {return 0;}')

    def test_transformed_main_has_only_one_entry(self):
        code, _ = transform_main(MAIN)
        self.assertEqual(code.count('void MX_Init(void)'), 1)
        self.assertEqual(code.count('int main(void)'), 0)

class GuardTests(WorkFlowTests):
    def test_preexisting_c_main_is_rejected(self):
        (self.output / 'src').mkdir(parents=True)
        (self.output / 'src/main.c').write_text('int main(void){return 1;}')
        p = plan(self.source, self.output, None, None, 'mxpio')
        self.assertTrue(any('src/main.c' in x for x in p.conflicts))
        self.assertFalse((self.output / 'src/main.cpp').exists())

    def test_ini_managed_edit_aborts(self):
        old = self._init()
        ini = self.output / 'platformio.ini'
        ini.write_text(ini.read_text().replace('framework = stm32cube', 'framework = arduino'))
        p = plan(self.source, self.output, old, old['config']['board'], 'mxpio')
        self.assertTrue(any('platformio.ini' in x for x in p.conflicts))

    def test_rollback_preserves_user_ini_modifications(self):
        old = self._init()
        (self.source / 'Core/Src/main.c').write_text(MAIN.replace('  MX_TIM2_Init();', '  MX_TIM2_Init();\n  MX_TIM3_Init();'))
        p = plan(self.source, self.output, old, old['config']['board'], 'mxpio')
        apply(self.output, p, old)
        ini = self.output / 'platformio.ini'
        ini.write_text(ini.read_text() + '\nmonitor_speed = 115200\n')
        rollback(self.output)
        self.assertIn("monitor_speed = 115200", ini.read_text())
