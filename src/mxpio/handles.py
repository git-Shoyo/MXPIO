"""Export CubeMX's public HAL handle objects without parsing function bodies."""
from __future__ import annotations

import re
from collections.abc import Callable, Iterator, Mapping


def _preprocessor(source: str, original: str) -> tuple[str, list[tuple[int, str, str]]]:
    """Hide directives from the C scanner; retain conditional branch paths."""
    chars = list(source)
    directives: list[tuple[int, str, str]] = []
    lines = source.splitlines(keepends=True)
    offset = 0
    index = 0
    while index < len(lines):
        line = lines[index]
        end = index + 1
        if line.lstrip().startswith('#'):
            while lines[end - 1].rstrip('\r\n').endswith('\\') and end < len(lines):
                end += 1
            text = ''.join(lines[index:end])
            directive = original[offset + line.index('#'):offset + len(text)]
            logical = re.sub(r'\\\r?\n', ' ', directive).strip()
            match = re.match(r'#\s*(if|ifdef|ifndef|elif|else|endif)\b(.*)', logical)
            if match:
                kind, expression = match.groups()
                directives.append((offset, kind, '#' + kind + expression.rstrip()))
            for pos in range(offset, offset + len(text)):
                if chars[pos] != '\n':
                    chars[pos] = ' '
        offset += sum(len(part) for part in lines[index:end])
        index = end
    return ''.join(chars), directives


def _statements(source: str) -> Iterator[tuple[int, str]]:
    """Yield file-scope declarations, skipping complete function bodies."""
    start = 0
    braces = parentheses = brackets = 0
    function_body = False
    for pos, char in enumerate(source):
        if char == '(':
            parentheses += 1
        elif char == ')':
            parentheses -= 1
        elif char == '[':
            brackets += 1
        elif char == ']':
            brackets -= 1
        elif char == '{':
            if braces == 0 and parentheses == 0 and brackets == 0:
                prefix = source[start:pos].strip()
                aggregate = re.match(r'(?:typedef\s+)?(?:struct|union|enum)\b', prefix)
                function_body = '=' not in prefix and not aggregate
            braces += 1
        elif char == '}':
            braces -= 1
            if braces == 0 and function_body:
                start = pos + 1
                function_body = False
        elif char == ';' and braces == parentheses == brackets == 0:
            yield start, source[start:pos + 1]
            start = pos + 1


def _split_top_level(text: str, separator: str) -> list[str]:
    result = []
    start = 0
    depth = 0
    for pos, char in enumerate(text):
        if char in '([{':
            depth += 1
        elif char in ')]}':
            depth -= 1
        elif char == separator and depth == 0:
            result.append(text[start:pos])
            start = pos + 1
    result.append(text[start:])
    return result


def _guards_at(directives: list[tuple[int, str, str]], offset: int) -> tuple[tuple[str, ...], ...]:
    stack: list[list[str]] = []
    for position, kind, text in directives:
        if position > offset:
            break
        if kind in ('if', 'ifdef', 'ifndef'):
            stack.append([text])
        elif kind in ('elif', 'else'):
            if not stack:
                raise ValueError('対応する#ifがない条件分岐です。')
            stack[-1].append(text)
        elif kind == 'endif':
            if not stack:
                raise ValueError('対応する#ifがない#endifです。')
            stack.pop()
    return tuple(tuple(branch) for branch in stack)


_HANDLE = re.compile(
    r'^\s*(?P<qualifiers>(?:(?:extern|static|const|volatile|__IO|__I|__O)\s+)*)'
    r'(?P<type>[A-Z][A-Z0-9_]*_HandleTypeDef)\s+(?P<body>.*?)\s*;\s*$', re.DOTALL)
_OBJECT = re.compile(
    r'(?:\*\s*(?:(?:const|volatile)\s+)*)*'
    r'[A-Za-z_]\w*(?:\s*\[[^\[\]]*\])*\s*$')


def generate_handles_header(sources: Mapping[str, str], mask: Callable[[str], str]) -> bytes:
    """Declare external HAL objects, preserving their conditional compilation.

    sources contains only the C files actually copied into the PlatformIO project.
    HAL types are supplied by main.h and its CubeMX HAL configuration.
    """
    lines = [
        '/* Generated by MXPIO. Do not edit; run mxpio sync instead. */',
        '#ifndef MXPIO_MX_HANDLES_H', '#define MXPIO_MX_HANDLES_H',
        '#include "main.h"', '#ifdef __cplusplus', 'extern "C" {', '#endif', '',
    ]
    seen = set()
    for filename, content in sorted(sources.items()):
        source, directives = _preprocessor(mask(content), content)
        for offset, statement in _statements(source):
            match = _HANDLE.fullmatch(statement)
            if not match:
                continue
            qualifiers = match['qualifiers'].split()
            if 'static' in qualifiers or 'extern' in qualifiers:
                continue
            guards = _guards_at(directives, offset + match.start('type'))
            prefix = ' '.join(['extern', *qualifiers, match['type']])
            for part in _split_top_level(match['body'], ','):
                declarator = _split_top_level(part, '=')[0].strip()
                if not _OBJECT.fullmatch(declarator):
                    # Functions returning a handle are not global handle objects.
                    if '(' in declarator:
                        continue
                    raise ValueError(f'{filename}: HALハンドル宣言を解析できません: {declarator}')
                declaration = f'{prefix} {declarator};'
                key = (guards, declaration)
                if key in seen:
                    continue
                seen.add(key)
                for branch in guards:
                    lines.extend(branch)
                lines.append(declaration)
                lines.extend('#endif' for _ in guards)
    lines.extend(['', '#ifdef __cplusplus', '}', '#endif', '#endif', ''])
    return '\n'.join(lines).encode('utf-8')
